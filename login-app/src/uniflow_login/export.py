from __future__ import annotations

import json
import os
import shutil
import tempfile
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

from .protocol import LoginError, LoginResult, Tenant, hostname


def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def server_config(tenant: Tenant, result: LoginResult, directory: Path, management_server: str, system_service: bool, managed: bool = False) -> str:
    management_server = hostname(management_server)
    token_path = Path("/var/lib/uniflow-ipp/token.json") if system_service else directory / "token.json"
    auth_path = Path("/var/lib/uniflow-ipp/auth-state.json") if system_service else directory / "auth-state.json"
    spool_path = Path("/var/spool/uniflow-ipp") if system_service else directory / "spool"
    credentials = result.credentials
    sections = {
        "server": {"listen": "127.0.0.1:8631", "spool_dir": str(spool_path)},
        "tenant": {
            "domain": tenant.domain,
            "installer_name": tenant.installer_name,
            "product_name": "uniFLOW IPP Server",
            "product_version": tenant.product_version,
        },
        "cups": {
            "queue_name": "uniflow_secure", "queue_display": tenant.secure_queue,
            "use_ipp": True, "ppd_path": "/usr/share/cups/model/uniflow-ipp.ppd", "share_queue": False,
        },
        "cloud": {
            "enabled": True,
            "tenant_domain": tenant.domain,
            "installer_id": tenant.installer_id,
            "secure_queue_name": tenant.secure_queue,
            "management_server": management_server,
            "user_id": credentials.user_id,
            **({"auth_state_path": str(auth_path)} if managed else {
                "token_path": str(token_path),
                "oauth_client_id": credentials.client_id,
                "oauth_client_secret": credentials.client_secret,
                "oauth_scope": credentials.scope,
                "token_endpoint": credentials.token_uri,
                "device_endpoint": "",
            }),
        },
    }
    lines = [
        "# Generated by uniFLOW Login. Keep private with its auth-state file.",
        "# Keep private; do not commit, email, or attach this file to bug reports.",
        f"# Peer credentials expire at {credentials.expires_at.isoformat()}; "
        + ("the service will attempt automatic renewal." if managed else "log in again before renewal is required."),
    ]
    for name, fields in sections.items():
        lines.extend(("", f"[{name}]"))
        for key, value in fields.items():
            encoded = str(value).lower() if isinstance(value, bool) else _toml_string(value)
            lines.append(f"{key} = {encoded}")
    return "\n".join(lines) + "\n"


def export_bundle(tenant: Tenant, result: LoginResult, parent: Path, management_server: str, system_service: bool = False, renewal_key: rsa.RSAPrivateKey | None = None) -> Path:
    now = datetime.now(timezone.utc)
    try:
        token_expiry = datetime.fromisoformat(result.token["expires_at"].replace("Z", "+00:00"))
    except (KeyError, TypeError, ValueError) as exc:
        raise LoginError("Cannot export a token with an invalid expiration.") from exc
    if token_expiry.tzinfo is None:
        raise LoginError("Token expiration must include a time zone.")
    if token_expiry <= now + timedelta(seconds=30) or result.credentials.expires_at <= now:
        raise LoginError("Authentication has expired; log in again before exporting.")
    try:
        parent = parent.resolve(strict=True)
        if not parent.is_dir():
            raise LoginError("Choose an existing export directory.")
        destination = parent / ("uniflow-config-" + uuid.uuid4().hex)
        config = server_config(tenant, result, destination, management_server, system_service, renewal_key is not None)
        if renewal_key is not None:
            if renewal_key.key_size != 2048 or not result.token.get("refresh_token"):
                raise LoginError("Automatic renewal requires the registration key and a refresh token.")
            state = {
                "version": 2,
                "tenant_domain": tenant.domain,
                "user_id": result.credentials.user_id,
                "peer": {
                    "client_id": result.credentials.client_id,
                    "client_secret": result.credentials.client_secret,
                    "scope": result.credentials.scope,
                    "token_uri": result.credentials.token_uri,
                    "redirect_uri": result.credentials.redirect_uri,
                    "expires_at": result.credentials.expires_at.isoformat().replace("+00:00", "Z"),
                },
                "token": result.token,
                "renewal_private_key_pem": renewal_key.private_bytes(
                    serialization.Encoding.PEM,
                    serialization.PrivateFormat.PKCS8,
                    serialization.NoEncryption(),
                ).decode("ascii"),
            }
            files = (("config.toml", config), ("auth-state.json", json.dumps(state, indent=2) + "\n"))
        else:
            files = (("config.toml", config), ("token.json", json.dumps(result.token, indent=2) + "\n"))
        staging = Path(tempfile.mkdtemp(prefix=".uniflow-export-", dir=parent))
        try:
            for name, data in files:
                fd = os.open(staging / name, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
                with os.fdopen(fd, "w", encoding="utf-8") as stream:
                    stream.write(data)
                    stream.flush()
                    os.fsync(stream.fileno())
            if not system_service:
                (staging / "spool").mkdir(mode=0o700)
            os.rename(staging, destination)
        finally:
            if staging.exists():
                shutil.rmtree(staging)
        return destination
    except OSError as exc:
        raise LoginError("Cannot export configuration. Check directory permissions and available disk space.") from exc
